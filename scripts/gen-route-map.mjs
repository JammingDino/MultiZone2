#!/usr/bin/env node
// Generate the command → route map the remote transport dispatches on.
//
//   node scripts/gen-route-map.mjs           # write src/lib/remote/routeMap.generated.ts
//   node scripts/gen-route-map.mjs --check   # fail if the checked-in file is stale
//
// Why generate rather than hand-write: `COVERAGE` in api/routes.rs already
// pairs every Tauri command with either the route that reaches it or a stated
// reason it is GUI-only, and a Rust test fails the build when a new command has
// neither. That table is the only complete, enforced statement of which command
// is which route — copying it into TypeScript by hand would produce a second
// one that silently disagrees, which is precisely the drift 0.11.0 spent a
// release ending.
//
// `--check` runs in the test suite, so a new command reaches the remote client
// in the same commit it reaches the app.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

export const COVERAGE_SOURCE = "src-tauri/src/api/routes.rs";
export const OUTPUT = "src/lib/remote/routeMap.generated.ts";

/**
 * Pull the COVERAGE entries out of routes.rs.
 *
 * A regex over Rust rather than a parser, for the same reason the Rust drift
 * test reads `generate_handler!` with `split_once`: the shape is a literal
 * array of two-element tuples written one per line, and it has been that shape
 * for six releases. If it ever stops being, `--check` fails loudly rather than
 * producing a map with holes in it — which is why the parser asserts a floor on
 * how many entries it found.
 */
export function parseCoverage(source) {
  const start = source.indexOf("pub const COVERAGE");
  if (start === -1) throw new Error(`no COVERAGE table in ${COVERAGE_SOURCE}`);
  const end = source.indexOf("\n];", start);
  if (end === -1) throw new Error("COVERAGE table is not terminated");
  const body = source.slice(start, end);

  const routed = [];
  const guiOnly = [];

  // The whitespace before the string matters: a long GuiOnly reason wraps onto
  // the next line, and four of them do. Requiring the quote to follow the
  // parenthesis directly silently dropped those commands from the map, which
  // made a remote client report them as unroutable rather than as GUI-only.
  const entry =
    /\(\s*"([a-z_0-9]+)::([a-z_0-9]+)"\s*,\s*(Route|GuiOnly)\(\s*"((?:[^"\\]|\\.)*)"/g;
  for (const m of body.matchAll(entry)) {
    const [, , command, kind, value] = m;
    if (kind === "GuiOnly") {
      guiOnly.push({ command, reason: value });
      continue;
    }
    // `METHOD /path` or `METHOD /path -> field`. The trailing field says the
    // route answers with the value wrapped in a one-key object; see the
    // `Coverage::Route` doc comment for the release that got away without it.
    const [route, unwrap] = value.split(" -> ");
    const space = route.indexOf(" ");
    routed.push({
      command,
      method: route.slice(0, space),
      path: route.slice(space + 1).trim(),
      ...(unwrap ? { unwrap: unwrap.trim() } : {}),
    });
  }

  if (routed.length < 80) {
    throw new Error(
      `parsed only ${routed.length} routed commands — has COVERAGE changed shape?`,
    );
  }
  return { routed, guiOnly };
}

/**
 * Two commands can share a route: `revoke_paired_device` and
 * `forget_paired_device` are both `DELETE /api/devices/:id`, told apart by a
 * query flag. That is fine in this direction — the map is keyed by command —
 * but a *duplicate command* would mean one of them silently wins.
 */
function assertNoDuplicateCommands(routed, guiOnly) {
  const seen = new Set();
  for (const { command } of [...routed, ...guiOnly]) {
    if (seen.has(command)) throw new Error(`${command} appears twice in COVERAGE`);
    seen.add(command);
  }
}

export function render({ routed, guiOnly }) {
  assertNoDuplicateCommands(routed, guiOnly);
  const byCommand = [...routed].sort((a, b) => a.command.localeCompare(b.command));
  const gui = [...guiOnly].sort((a, b) => a.command.localeCompare(b.command));

  const lines = [];
  lines.push("// GENERATED by scripts/gen-route-map.mjs — do not edit.");
  lines.push("//");
  lines.push("// Source of truth: src-tauri/src/api/routes.rs (COVERAGE). Regenerate with");
  lines.push("//   node scripts/gen-route-map.mjs");
  lines.push("// `npm test` fails when this file is stale, so a command that gains a route");
  lines.push("// reaches the remote client in the same commit it reaches the app.");
  lines.push("");
  lines.push("/** One command, and the route that serves it. */");
  lines.push("export interface RouteBinding {");
  lines.push("  method: string;");
  lines.push("  /** With `:param` placeholders, filled from the call's arguments. */");
  lines.push("  path: string;");
  lines.push("  /**");
  lines.push("   * The route answers `{ [unwrap]: value }` where the command returns the");
  lines.push("   * value itself, so the transport reads this key back out.");
  lines.push("   */");
  lines.push("  unwrap?: string;");
  lines.push("}");
  lines.push("");
  lines.push("export const ROUTE_MAP: Record<string, RouteBinding> = {");
  for (const r of byCommand) {
    const unwrap = r.unwrap ? `, unwrap: ${JSON.stringify(r.unwrap)}` : "";
    lines.push(
      `  ${r.command}: { method: ${JSON.stringify(r.method)}, path: ${JSON.stringify(r.path)}${unwrap} },`,
    );
  }
  lines.push("};");
  lines.push("");
  lines.push("/**");
  lines.push(" * Commands with no route, and why.");
  lines.push(" *");
  lines.push(" * Not a gap to fill later: each of these needs something only the machine");
  lines.push(" * running the app has — a file dialog, a microphone, a window. A remote");
  lines.push(" * client reads the reason and says so, which is a better answer than a");
  lines.push(" * request that fails with a 404.");
  lines.push(" */");
  lines.push("export const GUI_ONLY: Record<string, string> = {");
  for (const g of gui) {
    lines.push(`  ${g.command}: ${JSON.stringify(g.reason)},`);
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

export function generate(source) {
  return render(parseCoverage(source));
}

// ─── CLI ─────────────────────────────────────────────────────────────────────

const invokedDirectly = process.argv[1]?.endsWith("gen-route-map.mjs");
if (invokedDirectly) {
  const expected = generate(readFileSync(COVERAGE_SOURCE, "utf8"));
  if (process.argv.includes("--check")) {
    let actual = "";
    try {
      actual = readFileSync(OUTPUT, "utf8");
    } catch {}
    if (actual !== expected) {
      console.error(`${OUTPUT} is out of date. Run: node scripts/gen-route-map.mjs`);
      process.exit(1);
    }
    console.log(`${OUTPUT} is up to date`);
  } else {
    mkdirSync(dirname(OUTPUT), { recursive: true });
    writeFileSync(OUTPUT, expected);
    console.log(`wrote ${OUTPUT}`);
  }
}
